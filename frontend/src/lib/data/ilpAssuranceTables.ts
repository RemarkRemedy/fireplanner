export type IlpAssuranceRiskClass =
  | 'male-smoker'
  | 'male-non-smoker'
  | 'female-smoker'
  | 'female-non-smoker'

export interface IlpAssuranceRateTable {
  'male-smoker': number[]
  'male-non-smoker': number[]
  'female-smoker': number[]
  'female-non-smoker': number[]
}

function parseRateTableRows(rows: string): IlpAssuranceRateTable {
  const table: IlpAssuranceRateTable = {
    'male-smoker': [],
    'male-non-smoker': [],
    'female-smoker': [],
    'female-non-smoker': [],
  }

  for (const rawLine of rows.trim().split('\n')) {
    const line = rawLine.trim()
    if (!line) continue

    const matches = Array.from(line.matchAll(/(\d+\.\d+|\d+\+?)/g)).map((match) => match[0]!)
    if (matches.length !== 10 && matches.length !== 5) {
      throw new Error(`Invalid assurance rate row: ${line}`)
    }

    const pairs: Array<[number, number, number, number, number]> = matches.length === 5
      ? [[
          matches[0] === '120+' ? 120 : Number(matches[0]),
          Number(matches[1]),
          Number(matches[2]),
          Number(matches[3]),
          Number(matches[4]),
        ]]
      : [
          [
            matches[0] === '120+' ? 120 : Number(matches[0]),
            Number(matches[1]),
            Number(matches[2]),
            Number(matches[3]),
            Number(matches[4]),
          ],
          [
            matches[5] === '120+' ? 120 : Number(matches[5]),
            Number(matches[6]),
            Number(matches[7]),
            Number(matches[8]),
            Number(matches[9]),
          ],
        ]

    for (const [age, maleSmoker, maleNonSmoker, femaleSmoker, femaleNonSmoker] of pairs) {
      table['male-smoker'][age - 1] = maleSmoker
      table['male-non-smoker'][age - 1] = maleNonSmoker
      table['female-smoker'][age - 1] = femaleSmoker
      table['female-non-smoker'][age - 1] = femaleNonSmoker
    }
  }

  return table
}

function parseRateTableRowsNonSmokerFirst(rows: string): IlpAssuranceRateTable {
  const table: IlpAssuranceRateTable = {
    'male-smoker': [],
    'male-non-smoker': [],
    'female-smoker': [],
    'female-non-smoker': [],
  }

  for (const rawLine of rows.trim().split('\n')) {
    const line = rawLine.trim()
    if (!line) continue

    const matches = Array.from(line.matchAll(/(\d+\.\d+|\d+\+?)/g)).map((match) => match[0]!)
    if (matches.length !== 5) {
      throw new Error(`Invalid assurance rate row: ${line}`)
    }

    const age = Number(matches[0] === '120+' ? 120 : matches[0])
    const maleNonSmoker = Number(matches[1])
    const maleSmoker = Number(matches[2])
    const femaleNonSmoker = Number(matches[3])
    const femaleSmoker = Number(matches[4])

    if (age <= 0) {
      continue
    }

    const ageIndex = age - 1

    table['male-smoker'][ageIndex] = maleSmoker
    table['male-non-smoker'][ageIndex] = maleNonSmoker
    table['female-smoker'][ageIndex] = femaleSmoker
    table['female-non-smoker'][ageIndex] = femaleNonSmoker
  }

  return table
}

